"""
SQLAlchemy ORM models defining database tables.
"""

from datetime import datetime
from sqlalchemy import DateTime, Text, func
from sqlalchemy.orm import Mapped, mapped_column
from app.database import Base


class Summary(Base):
    """
    ORM Model for the 'summaries' table.
    Stores the original input text and the resulting AI-generated summary.
    """

    __tablename__ = "summaries"

    id: Mapped[int] = mapped_column(
        primary_key=True,
        index=True,
        autoincrement=True,
        doc="Unique primary key identifier for each summary record",
    )
    original_text: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="The source text submitted by the user",
    )
    generated_summary: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="The summary generated by the Gemini model",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        doc="Timestamp when the summary was generated and stored",
    )

    def __repr__(self) -> str:
        return f"<Summary(id={self.id}, created_at={self.created_at})>"
